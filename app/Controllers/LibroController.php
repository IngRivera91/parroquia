<?php

namespace App\Controllers;

use App\Class\BaseController;
use App\Class\Html;
use App\Models\Libro;
use App\Models\TipoActa;


class LibroController extends BaseController
{
    private array $tiposActa;
    public function __construct()
    {
        $this->model = Libro::class;
        $this->nameController = 'Libro';
        $this->nameModel = 'Libro';

        $this->tiposActa = TipoActa::query()->get()->toArray();

        $this->listaRelations = ['tipo_acta'];
        parent::__construct();
    }

    public function lista()
    {
        $this->breadcrumb = false;

        $this->filtroRelations = [
            'TipoActa' => 'tipo_acta'
        ];

        $this->filtroTableRelations = [
            'TipoActa' => 'tipos_acta'
        ];

        $this->camposLista = [
            'Id' => 'id',
            'Libro Numero' => 'numero',
            'Tipo Acta' => 'tipo_acta+label',
            'Activo' => 'activo'
        ];

        parent::lista();
    }

    public function generaInputFiltros (array $datosFiltros): void
    {
        $col = 3;
        $this->sizeColumnasInputsFiltros = $col;

        $datos['Libro+numero'] = '';
        $datos['TipoActa+id'] = '';

        foreach ($datosFiltros as $key => $filtro) {
            $datos[$key] = $filtro;
        }

        $placeholder = '';

        $tablaCampo = 'TipoActa+id';
        $this->htmlInputFiltros[$tablaCampo] = Html::selectConBuscador(
            'selectTipoActa',
            'id',
            'Tipo Acta',
            $tablaCampo,
            $col,
            $this->tiposActa,
            'label',
            $datos[$tablaCampo],
            1,
            ''
        );

        $tablaCampo = 'Libro+numero';
        $this->htmlInputFiltros[$tablaCampo] = Html::inputNumber($col,'Numero',1,$tablaCampo,$placeholder,$datos[$tablaCampo]);
    }

    public function registrar()
    {
        $this->breadcrumb = true;

        $this->htmlInputFormulario[] = Html::selectConBuscador(
            'id',
            'id',
            'Tipo Acta',
            'tipo_acta_id',
            4,
            $this->tiposActa,
            'label',
            '-1',
            1
        );

        $this->htmlInputFormulario[] = Html::inputNumberRequired(4,'Numero',1,'numero','','',true);

        $this->htmlInputFormulario[] = Html::inputNumberRequired(4,'Año inicio',1,'ano_inicio');
        $this->htmlInputFormulario[] = Html::inputNumberRequired(4,'Año fin',1,'ano_fin');

        $this->htmlInputFormulario[] = Html::selectActivo('Activo','activo',4,'1',2);

        $this->htmlInputFormulario[] = Html::submit('Registrar',$this->llaveFormulario,4);
    }

    public function registrarBd(bool $noRedirect = false)
    {
        $this->setPostLabel();
        return parent::registrarBd($noRedirect); // TODO: Change the autogenerated stub
    }

    public function modificar()
    {
        parent::obtenerRegistroArrayConGetRegistroId();
        $this->breadcrumb = true;

        $registro = $this->registro;

        $this->htmlInputFormulario[] = Html::selectConBuscador(
            'id',
            'id',
            'Tipo Acta',
            'tipo_acta_id',
            4,
            $this->tiposActa,
            'label',
            $registro['tipo_acta_id'],
            2
        );

        $this->htmlInputFormulario[] = Html::inputNumberRequired(4,'Numero',1,'numero','',$registro['numero'],true);

        $this->htmlInputFormulario[] = Html::inputNumberRequired(4,'Año inicio',1,'ano_inicio','',$registro['ano_inicio']);
        $this->htmlInputFormulario[] = Html::inputNumberRequired(4,'Año fin',1,'ano_fin','',$registro['ano_fin']);

        $this->htmlInputFormulario[] = Html::selectActivo('Activo','activo',4,$registro['activo'],2);
        $this->htmlInputFormulario[] = Html::submit('Modificar',$this->llaveFormulario,4);
    }

    public function modificarBd()
    {
        $this->setPostLabel();
        parent::modificarBd(); // TODO: Change the autogenerated stub
    }

    private function setPostLabel()
    {

        $tipo_acta_id = $_POST['tipo_acta_id'];
        $numero = $_POST['numero'];
        $inicio = $_POST['ano_inicio'];
        $fin = $_POST['ano_fin'];
        $registro = TipoActa::query()->find($tipo_acta_id)->toArray();
        $label = '';
        if (isset($registro['label'])) {
            $label = $registro['label'];
        }
        $_POST['description_select'] = "Libro {$numero} ({$label} {$inicio} - {$fin})";
    }

}
