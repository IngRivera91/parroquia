<?php

namespace App\Controllers;

use App\Class\BaseController;
use App\Class\Html;
use App\Class\Redireccion;
use App\Models\Menu;
use App\Models\Method;
use App\Models\MethodBase;
use App\Models\TipoActa;

class TipoActaController extends BaseController
{
    public function __construct()
    {
        $this->model = TipoActa::class;
        $this->nameController = 'TipoActa';
        $this->nameModel = 'TipoActa';
        parent::__construct();
    }

    public function lista()
    {
        $this->breadcrumb = false;

        $this->camposLista = [
            'Id' => 'id',
            'Tipo Acta' => 'label',
            'Numero Titulares' => 'numero_titulares',
            'Activo' => 'activo'
        ];

        parent::lista();
    }

    public function generaInputFiltros (array $datosFiltros): void
    {
        $col = 3;
        $this->sizeColumnasInputsFiltros = $col;

        $datos['TipoActa+label'] = '';

        foreach ($datosFiltros as $key => $filtro) {
            $datos[$key] = $filtro;
        }

        $tablaCampo = 'TipoActa+label';
        $placeholder = '';

        $this->htmlInputFiltros[$tablaCampo] = Html::inputText($col,'Tipo Acta',1,$tablaCampo,$placeholder,$datos[$tablaCampo]);
    }

    public function registrar()
    {
        $this->breadcrumb = true;

        $this->htmlInputFormulario[] = Html::inputTextRequired(4,'Tipo Acta',1,'label');
        $this->htmlInputFormulario[] = Html::inputNumberRequired(4,'Numero Titulares',2,'numero_titulares');
        $this->htmlInputFormulario[] = Html::selectActivo('Activo','activo',4,'1',2);

        $this->htmlInputFormulario[] = Html::submit('Registrar',$this->llaveFormulario,4);
    }

    private function setPostName()
    {
        $name = $_POST['label'];
        $name = str_replace(' ','_', $name);
        $_POST['name'] = strtolower($name);
    }

    public function registrarBd(bool $noRedirect = false)
    {
        $this->setPostName();
        parent::registrarBd($noRedirect);
    }

    public function modificar()
    {
        parent::obtenerRegistroArrayConGetRegistroId();
        $this->breadcrumb = true;

        $registro = $this->registro;

        $this->htmlInputFormulario[] = Html::inputTextRequired(4,'Tipo Acta',1,'label','',$registro['label']);
        $this->htmlInputFormulario[] = Html::inputTextRequired(4,'Numero Titulares',1,'numero_titulares','',$registro['numero_titulares']);
        $this->htmlInputFormulario[] = Html::selectActivo('Activo','activo',4,$registro['activo'],2);
        $this->htmlInputFormulario[] = Html::submit('Modificar',$this->llaveFormulario,4);
    }

    public function modificarBd()
    {
        $this->setPostName();
        parent::modificarBd(); // TODO: Change the autogenerated stub
    }

}
